#!/usr/bin/env python3
"""Installer validation tests that do not modify the host."""
import hashlib
import json
from pathlib import Path
import subprocess
import tarfile
import tempfile
import unittest

SCRIPT = Path(__file__).with_name('install.sh')
SOURCE = SCRIPT.read_text()
SNIPPETS = [chunk.split('\nPY\n', 1)[0] for chunk in SOURCE.split("<<'PY'\n")[1:]]


class InstallerTests(unittest.TestCase):
    def shell(self, code):
        return subprocess.run(['bash', '-c', 'source "$1"; ' + code, '_', str(SCRIPT)], capture_output=True, text=True)

    def test_plan_does_not_require_root_or_linux(self):
        result = subprocess.run(['bash', str(SCRIPT), '--version', 'v1.2.3-beta.1', '--plan'], capture_output=True, text=True)
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertIn('127.0.0.1:8080', result.stdout)

    def test_bad_arguments_fail(self):
        for args in ('--version', '--version ../../bad', '--version v1.2.3 --bundle-dir /tmp/bundle', '--unknown', '--bundle-dir --plan'):
            with self.subTest(args=args):
                self.assertNotEqual(self.shell('parse_args '+args).returncode, 0)

    def test_platform_support(self):
        for name, expected in [('x86_64','amd64'), ('aarch64','arm64')]:
            self.assertEqual(self.shell('platform_arch '+name).stdout, expected)
        self.assertNotEqual(self.shell('platform_arch riscv64').returncode, 0)
        self.assertEqual(self.shell('supported_os debian 12').returncode, 0)
        self.assertNotEqual(self.shell('supported_os ubuntu 20.04').returncode, 0)

    def test_service_uses_local_database_and_unprivileged_account(self):
        result = self.shell('pg_service=postgresql@16-zela.service; write_unit')
        self.assertEqual(result.returncode, 0)
        for value in ('Requires=postgresql@16-zela.service', 'User=zela', '--listen 127.0.0.1:8080', 'ProtectSystem=strict', 'StateDirectoryMode=0700'):
            self.assertIn(value, result.stdout)

    def test_rhel_family_versions(self):
        for distro in ('rhel', 'rocky', 'almalinux'):
            for version in ('9', '9.6', '10', '10.1'):
                with self.subTest(distro=distro, version=version):
                    self.assertEqual(self.shell('supported_os '+distro+' '+version).returncode, 0)
                    self.assertEqual(self.shell('os_family '+distro).stdout, 'rpm')
            self.assertNotEqual(self.shell('supported_os '+distro+' 8.10').returncode, 0)
        self.assertNotEqual(self.shell('supported_os fedora 42').returncode, 0)

    def test_package_manager_dispatch(self):
        mocks = 'apt-get() { echo "apt:$*"; }; dnf() { echo "dnf:$*"; }; '
        debian = self.shell(mocks+'family=debian; install_packages')
        self.assertEqual(debian.returncode, 0, debian.stderr)
        self.assertIn('apt:install', debian.stdout)
        self.assertNotIn('dnf:', debian.stdout)
        rpm = self.shell(mocks+'family=rpm; install_packages')
        self.assertEqual(rpm.returncode, 0, rpm.stderr)
        self.assertIn('postgresql-server postgresql policycoreutils', rpm.stdout)
        self.assertIn('openssh-clients', rpm.stdout)
        self.assertNotIn('apt:', rpm.stdout)
        self.assertNotIn('module reset', rpm.stdout)

    def test_rpm_database_service_and_manager_dependency(self):
        database = self.shell('write_rpm_database_unit')
        self.assertEqual(database.returncode, 0, database.stderr)
        for setting in ('User=postgres', 'ExecStart=/usr/bin/postgres -D /var/lib/pgsql/zela', 'RuntimeDirectory=postgresql', 'RuntimeDirectoryPreserve=yes'):
            self.assertIn(setting, database.stdout)
        manager = self.shell('pg_service=postgresql-zela.service; write_unit')
        self.assertIn('Requires=postgresql-zela.service', manager.stdout)
        self.assertNotIn('postgresql@', manager.stdout)

    def test_rpm_database_initialization_and_repeat_preserve_data(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            # Redirect filesystem paths in an isolated copy, never the production script.
            source = SOURCE
            for path in ('/var/lib/pgsql', '/etc/systemd/system', '/run/postgresql'):
                source = source.replace(path, str(root)+path)
                (root/path.lstrip('/')).mkdir(parents=True, exist_ok=True)
            copy = root/'install.sh'
            copy.write_text(source)
            mocks = r'''source "$1"
family=rpm
pg_version=16
install() { mkdir -p "${@: -1}"; }
chown() { :; }
restorecon() { echo "restorecon:$*"; }
systemctl() { echo "systemctl:$*"; }
runuser() {
  if [[ "$4" == /usr/bin/initdb ]]; then
    echo initialized
    printf '16\n' > "$6/PG_VERSION"
    printf '# generated by initdb\n' > "$6/postgresql.conf"
  fi
}
prepare_database
printf 'retained' > "$2/var/lib/pgsql/zela/data-probe"
prepare_database
'''
            result = subprocess.run(['bash','-c',mocks,'_',str(copy),str(root)], capture_output=True, text=True)
            self.assertEqual(result.returncode, 0, result.stderr)
            self.assertEqual(result.stdout.count('initialized'), 1)
            self.assertIn('restorecon:', result.stdout)
            self.assertIn('systemctl:enable --now postgresql-zela.service', result.stdout)
            data = root/'var/lib/pgsql/zela'
            self.assertEqual((data/'data-probe').read_text(), 'retained')
            self.assertEqual((data/'postgresql.conf').read_text().count("include = 'zela.conf'"), 1)
            self.assertIn("listen_addresses = ''", (data/'zela.conf').read_text())
            # A different on-disk major must be refused, without reinitialization.
            (data/'PG_VERSION').write_text('15\n')
            result = subprocess.run(['bash','-c',mocks,'_',str(copy),str(root)], capture_output=True, text=True)
            self.assertNotEqual(result.returncode, 0)
            self.assertIn('major version mismatch', result.stderr)
            self.assertNotIn('initialized', result.stdout)

    def fixture(self, root):
        (root/'bin').mkdir()
        (root/'BUILD.json').write_text(json.dumps(dict(version='v1.2.3', os='linux', arch='amd64')))
        for name, machine in [('zela',62),('zela-server',62),('zela-worker-linux-amd64',62),('zela-worker-linux-arm64',183)]:
            header = b'\x7fELF\x02\x01'+bytes(12)+machine.to_bytes(2,'little')
            (root/'bin'/name).write_bytes(header)

    def validate(self, root, arch='amd64', version='v1.2.3'):
        return subprocess.run(['python3','-c', SNIPPETS[1], str(root), arch, version], capture_output=True, text=True)

    def test_bundle_checks_metadata_cpu_and_symlinks(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            self.fixture(root)
            self.assertEqual(self.validate(root).returncode, 0)
            self.assertNotEqual(self.validate(root, arch='arm64').returncode, 0)
            self.assertNotEqual(self.validate(root, version='v9.9.9').returncode, 0)
            (root/'bin/zela').unlink()
            (root/'bin/zela').symlink_to(root/'bin/zela-server')
            self.assertNotEqual(self.validate(root).returncode, 0)

    def test_download_rejects_checksum_mismatch_and_archive_links(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            name = 'zela-v1.2.3-linux-amd64.tar.gz'
            with tarfile.open(root/name, 'w:gz') as tar:
                member = tarfile.TarInfo(name[:-7]+'/BUILD.json')
                member.type, member.linkname = tarfile.SYMTYPE, '/etc/passwd'
                tar.addfile(member)
            checksum = root/'SHA256SUMS'
            checksum.write_text('0'*64+'  '+name+'\n')
            def extract():
                return subprocess.run(['python3','-c',SNIPPETS[0],str(root),name], capture_output=True, text=True)
            self.assertIn('checksum verification failed', extract().stderr)
            checksum.write_text(hashlib.sha256((root/name).read_bytes()).hexdigest()+'  '+name+'\n')
            result = extract()
            self.assertNotEqual(result.returncode, 0)
            self.assertIn('non-regular file', result.stderr)


if __name__ == '__main__':
    unittest.main()
